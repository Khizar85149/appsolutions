/**
 * Writes supabase/seed.sql from the content bundled in src/content.
 *
 *   npm run db:seed-file
 *
 * Run it again whenever src/content changes and you want a fresh seed file.
 * The generated SQL never overwrites rows that already exist in the database.
 */
import { writeFileSync } from "node:fs";
import { jobs } from "../src/content/careers.ts";
import { caseStudies } from "../src/content/case-studies.ts";
import { consultations } from "../src/content/consultations.ts";
import { industries } from "../src/content/industries.ts";
import { services } from "../src/content/services.ts";
import {
  caseStudyToRow,
  consultationToRow,
  industryToRow,
  jobToRow,
  serviceToRow,
} from "../src/server/mappers.ts";

/** Columns stored as jsonb. Every other array column is text[]. */
const JSONB = new Set([
  "outcomes",
  "deliverables",
  "process",
  "engagement",
  "faqs",
  "stats",
  "challenges",
  "solutions",
  "hero_metric",
  "metrics",
  "approach",
  "quote",
]);

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;

function literal(column, value) {
  if (value === null || value === undefined) return "null";
  if (JSONB.has(column)) return `${quote(JSON.stringify(value))}::jsonb`;
  if (Array.isArray(value)) return value.length ? `array[${value.map(quote).join(", ")}]::text[]` : "'{}'::text[]";
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  return quote(value);
}

function insert(table, rows) {
  if (rows.length === 0) return "";
  const columns = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${columns.map((c) => literal(c, r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table}\n  (${columns.join(", ")})\nvalues\n${values}\non conflict (slug) do nothing;\n`;
}

// Positions go up in tens so a row can be placed between two others later.
const rows = (items, toRow) => items.map((item, i) => toRow(item, (i + 1) * 10));

const sql = `-- =====================================================================
-- Apps Solutions Tech: starting content
--
-- GENERATED by scripts/build-seed.mjs from src/content. Do not edit by hand.
-- Run once in Supabase (SQL Editor) after supabase/schema.sql.
-- Rows that already exist are left untouched, so it is safe to run again.
-- =====================================================================

${insert("services", rows(services, serviceToRow))}
${insert("industries", rows(industries, industryToRow))}
${insert("case_studies", rows(caseStudies, caseStudyToRow))}
${insert("jobs", rows(jobs, jobToRow))}
${insert("consultation_types", rows(consultations, consultationToRow))}`;

const out = new URL("../supabase/seed.sql", import.meta.url);
writeFileSync(out, sql);
console.log(
  `supabase/seed.sql written: ${services.length} services, ${industries.length} industries, ` +
    `${caseStudies.length} case studies, ${jobs.length} jobs, ${consultations.length} consultation types.`,
);
